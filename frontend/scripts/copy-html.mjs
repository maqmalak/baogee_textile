// After `vite build`: copy the built index.html to baogee_textile/www/baogee.html so Frappe serves the SPA at /baogee
// (hooks.py → website_route_rules sends /baogee/* there too). Frappe renders it as Jinja on each request.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const built = resolve(here, "../../baogee_textile/public/frontend/index.html");
const target = resolve(here, "../../baogee_textile/www/baogee.html");
const html = readFileSync(built, "utf8").replace("</head>", "  <script>window.csrf_token = '{{ frappe.session.csrf_token }}';</script>\n  </head>");
writeFileSync(target, "{# Generated by frontend/scripts/copy-html.mjs — edit frontend/index.html instead #}\n" + html);
console.log("wrote", target);
